CREATE TABLE IF NOT EXISTS postings (
    id TEXT PRIMARY KEY,
    source TEXT,
    company TEXT,
    title TEXT,
    ncs JSONB NOT NULL,
    it_only BOOLEAN,
    region TEXT,
    hire_type TEXT,
    career TEXT,
    education TEXT,
    headcount TEXT,
    posted_at DATE,
    close_at DATE,
    source_ongoing BOOLEAN,
    active_as_of DATE NOT NULL,
    is_active BOOLEAN NOT NULL,
    url TEXT,
    body TEXT
);

CREATE INDEX IF NOT EXISTS postings_active_deadline_idx
    ON postings (close_at, id) WHERE is_active;

CREATE OR REPLACE VIEW active_postings AS
    SELECT * FROM postings WHERE is_active;

CREATE TABLE IF NOT EXISTS posting_extractions (
    posting_id TEXT PRIMARY KEY REFERENCES postings(id) ON DELETE CASCADE,
    job_areas JSONB NOT NULL,
    it_relevant BOOLEAN,
    min_experience_years NUMERIC,
    entry_level_ok BOOLEAN,
    meta JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS competencies (
    posting_id TEXT NOT NULL REFERENCES posting_extractions(posting_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    competency_type TEXT NOT NULL,
    requirement TEXT NOT NULL,
    position TEXT NOT NULL,
    raw_name TEXT,
    evidence TEXT,
    PRIMARY KEY (posting_id, name, competency_type, requirement, position)
);

CREATE INDEX IF NOT EXISTS competencies_skill_idx ON competencies (competency_type, name);

CREATE TABLE IF NOT EXISTS ncs_map_skills (
    skill TEXT PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS ncs_map (
    skill TEXT NOT NULL REFERENCES ncs_map_skills (skill) ON DELETE CASCADE,
    rank INTEGER NOT NULL CHECK (rank > 0),
    unit_code TEXT NOT NULL,
    unit_name TEXT NOT NULL,
    score DOUBLE PRECISION NOT NULL CHECK (score BETWEEN -1 AND 1),
    backend TEXT,
    catalog TEXT,
    competency_type TEXT,
    competency_types JSONB NOT NULL,
    PRIMARY KEY (skill, unit_code),
    UNIQUE (skill, rank)
);

CREATE TABLE IF NOT EXISTS ncs_match_coverage (
    as_of DATE PRIMARY KEY,
    posting_total INTEGER NOT NULL CHECK (posting_total >= 0),
    analyzed_posting_count INTEGER NOT NULL CHECK (analyzed_posting_count BETWEEN 0 AND posting_total),
    report JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS demand_coverage (
    scope TEXT NOT NULL CHECK (scope IN ('overall', 'region', 'hire_type', 'region_hire_type')),
    region TEXT NOT NULL,
    hire_type TEXT NOT NULL,
    posting_total INTEGER NOT NULL CHECK (posting_total >= 0),
    analyzed_posting_count INTEGER NOT NULL CHECK (analyzed_posting_count BETWEEN 0 AND posting_total),
    coverage_pct NUMERIC NOT NULL CHECK (coverage_pct BETWEEN 0 AND 100),
    PRIMARY KEY (scope, region, hire_type)
);

CREATE TABLE IF NOT EXISTS demand (
    scope TEXT NOT NULL,
    region TEXT NOT NULL,
    hire_type TEXT NOT NULL,
    skill TEXT NOT NULL,
    competency_type TEXT NOT NULL,
    posting_count INTEGER NOT NULL CHECK (posting_count BETWEEN 0 AND analyzed_posting_count),
    required_posting_count INTEGER NOT NULL CHECK (required_posting_count BETWEEN 0 AND posting_count),
    alternative_required_posting_count INTEGER NOT NULL CHECK (alternative_required_posting_count BETWEEN 0 AND posting_count),
    preferred_posting_count INTEGER NOT NULL CHECK (preferred_posting_count BETWEEN 0 AND posting_count),
    analyzed_posting_count INTEGER NOT NULL CHECK (analyzed_posting_count BETWEEN 0 AND posting_total),
    posting_total INTEGER NOT NULL,
    demand_pct NUMERIC NOT NULL CHECK (demand_pct BETWEEN 0 AND 100),
    PRIMARY KEY (scope, region, hire_type, skill, competency_type),
    FOREIGN KEY (scope, region, hire_type) REFERENCES demand_coverage (scope, region, hire_type) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS demand_skill_idx ON demand (competency_type, skill);

